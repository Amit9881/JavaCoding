package Casting;

public class narroCasting {
    public static void main(String[] args){
        double x = 99.99;
        double y = 99.48;

        System.out.println(x);
        System.out.println(y);

        int a = (int) x;
        int b = (int) y;

        System.out.println(a);
        System.out.println(b);
    }
}
